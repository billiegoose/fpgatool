"""Regenerate the compact synthetic dump fixture using the real MFS1 writer."""
import json
from itertools import groupby
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from programming.mini_filesystem import MiniFileSystem, encode_entry, content_id

START, END, SECTOR = 0x220000, 0x400000, 0x10000
INDEX_START = 0x240000
DATA_START = INDEX_START + SECTOR


class MemoryFlash:
    def __init__(self):
        self.data = bytearray(b'\xff' * END)

    def read(self, address, length):
        return bytes(self.data[address:address + length])

    def program(self, address, data):
        assert all(old & new == new for old, new in zip(self.read(address, len(data)), data))
        self.data[address:address + len(data)] = data

    clear_bits = program


def build_demo():
    flash = MemoryFlash()
    fs = MiniFileSystem(flash, start=INDEX_START, end=END, sector_size=SECTOR,
                        legacy_start=START)
    def add(name, length, fill, kind=0):
        return fs.add(bytes([fill]) * length, name, kind)[0]
    add('boot-scene.bin', 39322, 0x31, 3)  # 60% of the first data sector.
    add('readme.txt', 520, 0x41, 1)
    add('settings.txt', 83, 0x42, 1)
    add('palette.bin', 256, 0x43)
    add('red2-regular.bin', 4300, 0x44, 2)
    add('red2-ui.bin', 4300, 0x44, 2)  # Alias, no new flash allocation.
    add('splash.bin', 16400, 0x45, 3)
    add('amber-components.bin', 103180, 0x46, 3)
    add('glyph-cache.bin', 24576, 0x47, 2)
    for n in range(12):
        add(f'panel-{n + 1:02}.txt', 60 + n * 37, 0x50 + n, 1)
    add('boot-scene.bin', 33000, 0x70, 3)  # Old content stays on flash.
    add('readme.txt', 780, 0x71, 1)
    add('waveform.bin', 170000, 0x72)
    add('empty.txt', 0, 0, 1)
    entries, slot = fs.read_index()
    flash.program(INDEX_START + 256 + slot * 64, b'\x01\x02\x03')  # Interrupted index write.
    add('recovery.txt', 1500, 0x73, 1)
    # Register preserved assets on both sides of the first erase boundary.
    flash.program(START, bytes([0x74]) * 4300)
    fs.register_existing(START, 4300, 'legacy-font.bin', 2)
    flash.program(START + SECTOR, bytes([0x75]) * 39322)
    fs.register_existing(START + SECTOR, 39322, 'legacy-scene.bin', 3)
    # A committed entry with bad CRC should remain visible as a diagnostic.
    _, slot = fs.read_index()
    raw = bytearray(encode_entry(1, content_id(b'bad'), DATA_START, 3, b'damaged.txt'))
    raw[58] ^= 1
    flash.program(INDEX_START + 256 + slot * 64, raw)
    flash.program(START + 12 * SECTOR, bytes([0x29]) * 700)  # Unreferenced programmed pages.
    records = []
    for slot in range(1020):
        raw = flash.read(INDEX_START + 256 + slot * 64, 64)
        if raw != b'\xff' * 64:
            records.append({'slot': slot, 'hex': raw.hex()})
    segments = []
    for start, end in [(START, INDEX_START), (DATA_START, END)]:
        address = start
        for fill, run in groupby(flash.data[start:end]):
            length = sum(1 for _ in run)
            if fill != 255:
                segments.append({'address': address, 'length': length, 'fill': fill})
            address += length
    return {'description': 'Synthetic MFS1 image generated by the host writer; not a board capture.', 'records': records, 'segments': segments}


if __name__ == '__main__':
    result = json.dumps(build_demo(), indent=2) + '\n'
    if '--stdout' in sys.argv:
        print(result, end='')
    else:
        Path(__file__).with_name('demo.json').write_text(result)
